"""
Parse LISTADO DE IGLESIAS.xlsx into churches-data.ts
Yellow fill (FFFFFF00) in column C = Convención Regional header
Column D = unique code (conventions and churches)
Blank rows = separators between conventions
Zone headers (ZN I, ZN II...) = ignored (no yellow fill, no code)
"""
import re
import sys
import openpyxl
from pathlib import Path

EXCEL_PATH = Path.home() / "Downloads" / "LISTADO DE IGLESIAS.xlsx"
OUT_PATH = Path(__file__).parent.parent / "packages/api/src/data/churches-data.ts"

YELLOW_RGB = "FFFFFF00"


def is_yellow(cell) -> bool:
    fill = cell.fill
    if not fill:
        return False
    if fill.fgColor.type == "rgb" and fill.fgColor.rgb == YELLOW_RGB:
        return True
    return False


def slugify(text: str) -> str:
    text = text.strip().lower()
    text = re.sub(r"[^a-z0-9\s-]", "", text)
    text = re.sub(r"[\s]+", "-", text)
    text = re.sub(r"-+", "-", text)
    return text[:60].strip("-")


def first_line(text: str) -> str:
    return text.split("\n")[0].strip().split(",")[0].strip()


def escape_ts_string(s: str) -> str:
    return s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")


def main():
    wb = openpyxl.load_workbook(EXCEL_PATH)
    ws = wb.active

    conventions = []
    current = None
    seen_conv_ids = {}
    seen_church_ids = {}

    for row in ws.iter_rows(min_row=1):
        col_c = row[2] if len(row) > 2 else None
        col_d = row[3] if len(row) > 3 else None

        val_c = str(col_c.value or "").strip() if col_c else ""
        val_d = str(col_d.value or "").strip() if col_d else ""

        # Skip blank rows
        if not val_c:
            continue

        name_c = first_line(val_c)

        if is_yellow(col_c):
            # Convención Regional header
            raw_id = val_d if val_d else slugify(name_c)
            # Deduplicate
            if raw_id in seen_conv_ids:
                seen_conv_ids[raw_id] += 1
                conv_id = f"{raw_id}-{seen_conv_ids[raw_id]}"
            else:
                seen_conv_ids[raw_id] = 0
                conv_id = raw_id

            current = {
                "id": conv_id,
                "name": name_c,
                "code": val_d,
                "churches": [],
            }
            conventions.append(current)
        else:
            # Could be a zone header (no convention yet, no code, short name starting with ZN)
            if current is None:
                continue

            # Church row
            raw_id = val_d if val_d else slugify(name_c)
            if raw_id in seen_church_ids:
                seen_church_ids[raw_id] += 1
                church_id = f"{raw_id}-{seen_church_ids[raw_id]}"
            else:
                seen_church_ids[raw_id] = 0
                church_id = raw_id

            current["churches"].append({
                "id": church_id,
                "name": name_c,
                "code": val_d if val_d else None,
            })

    # Generate TypeScript
    lines = [
        "// AUTO-GENERATED by scripts/parse-churches.py — do not edit manually",
        "",
        "export interface ConventionData {",
        "  id: string",
        "  name: string",
        "  code: string",
        "}",
        "",
        "export interface ChurchData {",
        "  id: string",
        "  name: string",
        "  code: string | null",
        "}",
        "",
        "export interface ConventionWithChurches extends ConventionData {",
        "  churches: ChurchData[]",
        "}",
        "",
        "export const CONVENTIONS: ConventionWithChurches[] = [",
    ]

    for conv in conventions:
        lines.append("  {")
        lines.append(f"    id: `{escape_ts_string(conv['id'])}`,")
        lines.append(f"    name: `{escape_ts_string(conv['name'])}`,")
        lines.append(f"    code: `{escape_ts_string(conv['code'])}`,")
        lines.append("    churches: [")
        for ch in conv["churches"]:
            code_val = f"`{escape_ts_string(ch['code'])}`" if ch["code"] else "null"
            lines.append("      {")
            lines.append(f"        id: `{escape_ts_string(ch['id'])}`,")
            lines.append(f"        name: `{escape_ts_string(ch['name'])}`,")
            lines.append(f"        code: {code_val},")
            lines.append("      },")
        lines.append("    ],")
        lines.append("  },")

    lines.append("]")
    lines.append("")

    OUT_PATH.write_text("\n".join(lines), encoding="utf-8")

    total_churches = sum(len(c["churches"]) for c in conventions)
    print(f"Done: {len(conventions)} conventions, {total_churches} churches → {OUT_PATH}")


if __name__ == "__main__":
    main()
