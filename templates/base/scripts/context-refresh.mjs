#!/usr/bin/env node

import { readFile, writeFile, mkdir, access } from 'node:fs/promises'
import { join } from 'node:path'

const root = process.cwd()
const checkOnly = process.argv.includes('--check')
const agentDir = join(root, 'docs', 'agent')
const manifestPath = join(agentDir, 'project-manifest.json')

async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

async function readJson(path, fallback = {}) {
  try {
    return JSON.parse(await readFile(path, 'utf8'))
  } catch {
    return fallback
  }
}

async function readText(path) {
  try {
    return await readFile(path, 'utf8')
  } catch {
    return ''
  }
}

async function listWorkspaces() {
  const workspaces = ['apps/portal', 'apps/admin', 'packages/api', 'packages/shared']
  const present = []
  for (const workspace of workspaces) {
    if (await exists(join(root, workspace, 'package.json'))) present.push(workspace)
  }
  return present
}

function listRoutes(serverless) {
  const routes = []
  let path = null
  for (const line of serverless.split(/\r?\n/)) {
    const pathMatch = line.match(/^\s+path:\s*(\S+)\s*$/)
    if (pathMatch) {
      path = pathMatch[1]
      continue
    }
    const methodMatch = line.match(/^\s+method:\s*(\S+)\s*$/)
    if (methodMatch && path) {
      routes.push({ method: methodMatch[1].toUpperCase(), path })
      path = null
    }
  }
  return routes.sort((a, b) => `${a.method}:${a.path}`.localeCompare(`${b.method}:${b.path}`))
}

function listFirestoreMatches(rules) {
  return [...rules.matchAll(/match\s+\/([^\s{]+)/g)]
    .map((match) => match[1])
    .filter((value) => value !== 'databases')
    .sort()
}

async function collectInventory() {
  const serverless = await readText(join(root, 'packages', 'api', 'serverless.yml'))
  const rules = await readText(join(root, 'firestore.rules'))
  const indexes = await readJson(join(root, 'firestore.indexes.json'), { indexes: [] })
  return {
    workspaces: await listWorkspaces(),
    routes: listRoutes(serverless),
    firestoreMatches: listFirestoreMatches(rules),
    firestoreIndexCount: Array.isArray(indexes.indexes) ? indexes.indexes.length : 0,
  }
}

function renderContext(manifest) {
  return `# Generated project context

This file is generated by \`unbj-echo\` and is safe to load at task start.

- Project: \`${manifest.projectName}\`
- Event: \`${manifest.eventName}\`
- Archetype: \`${manifest.archetype}\`
- Languages: \`${manifest.languages}\`
- Modules: \`${manifest.modules.length ? manifest.modules.join(', ') : 'none'}\`
- Local portal/admin/API ports: \`3000\`, \`3002\`, \`3001\`

The machine-readable inventory is \`docs/agent/project-manifest.json\`. Run
\`pnpm context:refresh\` after adding routes, workspaces, indexes, or modules;
run \`pnpm context:check\` to detect stale generated context.
`
}

function renderArchitecture(manifest) {
  const modules = manifest.modules.length ? manifest.modules.join(', ') : 'none'
  return `# Architecture reference

## Workspaces

${manifest.inventory.workspaces.map((workspace) => `- \`${workspace}\``).join('\n')}

## Data flow

The browser calls the API for registration, payment, administration, and
mutations. Firebase Admin is used only by the API. Firebase Client is limited to
approved authentication and real-time projections. Stripe webhooks are the
payment source of truth; Resend sends transactional/admin email.

## Generated configuration

- Archetype: \`${manifest.archetype}\`
- Languages: \`${manifest.languages}\`
- Enabled modules: ${modules}
`
}

